
const mongoose = require("mongoose");

const notificationSchema = new mongoose.Schema(
  {
    recipient: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },
    actor: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    title: {
      type: String,
      required: true,
      trim: true,
    },
    message: {
      type: String,
      required: true,
      trim: true,
    },
    type: {
      type: String,
      enum: [
        "CLAIM_SUBMITTED",
        "CLAIM_APPROVED",
        "CLAIM_REJECTED",
        "CLAIM_RETURNED",
        "CLAIM_SANCTIONED",
        "PAYMENT_COMPLETED",
        "GENERAL",
      ],
      default: "GENERAL",
    },
    claimId: {
      type: mongoose.Schema.Types.ObjectId,
      default: null,
    },
    claimType: {
      type: String,
      default: null,
    },
    link: {
      type: String,
      default: null,
    },
    metadata: {
      type: mongoose.Schema.Types.Mixed,
      default: {},
    },
    readAt: {
      type: Date,
      default: null,
    },
  },
  { timestamps: true }
);

notificationSchema.index({ recipient: 1, createdAt: -1 });
notificationSchema.index({ recipient: 1, readAt: 1 });

module.exports = mongoose.model("Notification", notificationSchema);
